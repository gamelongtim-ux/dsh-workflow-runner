#!/usr/bin/env node
// Vendor ZCode's dynamic-workflow packages into this repo.
//
// Two upstream packages are needed to run a ZCode Dynamic Workflow:
//
//   packages/dynamic-workflow/          the engine: analysis, compiler, lowering, schema, facade
//   packages/dynamic-workflow-runtime/  the harness: child process + NDJSON bridge + vm cell
//
// Both are copied from a ZCode checkout and kept byte-identical to upstream, with
// exactly one documented exception: the runtime package imports the engine by its
// workspace package name, which does not exist here. The specifier is rewritten to a
// relative path. The rewrite is recorded in the manifest (post-rewrite hashes), so
// drift is still detected, and the script prints exactly what it changed.
//
//   node scripts/vendor-dynamic-workflow.mjs --from <path-to-zcode-checkout>   sync
//   node scripts/vendor-dynamic-workflow.mjs --verify                            integrity check
//
// --from expects the ZCode repo checkout. The packages live at
//   <repo>/apps/zcode-cli/packages/dynamic-workflow
//   <repo>/apps/zcode-cli/packages/dynamic-workflow-runtime
// but any directory containing src/ works.
//
// --verify re-hashes the vendored tree and compares it against the manifests. It
// fails if anything drifted — the guard against accidentally editing upstream code,
// and against forgetting to re-sync after bumping the pinned upstream revision.
//
// Upstream's own test corpus is not vendored: it is large and is exercised from the
// spike workspace, not from the published plugin.

import { createHash } from 'node:crypto';
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
  copyFileSync,
} from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, '..');
const packagesRoot = join(repoRoot, 'packages');

/**
 * The upstream packages, in dependency order.
 *
 * `rewriteImport` is the one mechanical change applied to vendored sources: it maps
 * the upstream workspace specifier onto a relative path inside this repo. It is
 * deliberately narrow — a specifier swap, nothing else.
 */
const PACKAGES = [
  {
    dir: 'dynamic-workflow',
    upstream: 'apps/zcode-cli/packages/dynamic-workflow',
    // Upstream's own package.json names a workspace dependency we do not have.
    rewriteImport: null,
    localFiles: ['package.json', 'tsconfig.runtime.json'],
    // The build-time stdlib generator is part of the upstream package and is
    // required to build the vendored engine.
    extraFiles: ['scripts/generate-libs.mjs'],
    // Build artifacts: generated by `npm run build`, not authored upstream.
    generatedFiles: ['src/compiler/libs.generated.ts'],
    docs: ['docs/analysis.md', 'docs/execution-engine.md', 'README.md'],
  },
  {
    dir: 'dynamic-workflow-runtime',
    upstream: 'apps/zcode-cli/packages/dynamic-workflow-runtime',
    // The harness imports the engine by its workspace package name.
    // The relative path must hold for BOTH the source location (src/) and the
    // emitted location (dist/) — tsc keeps rootDir and outDir at the same depth,
    // so ../../dynamic-workflow/dist/index.js resolves to the engine's dist from
    // either side.
    rewriteImport: {
      from: '"@zcode/dynamic-workflow"',
      to: '"../../dynamic-workflow/dist/index.js"',
    },
    localFiles: ['package.json'],
    extraFiles: [],
    generatedFiles: [],
    docs: ['README.md'],
  },
];

function parseArgs(argv) {
  const args = { from: null, verify: false };
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === '--from') {
      args.from = argv[i + 1];
      i += 1;
    } else if (argv[i] === '--verify') {
      args.verify = true;
    } else if (argv[i] === '--help' || argv[i] === '-h') {
      process.stdout.write(
        'usage: vendor-dynamic-workflow.mjs --from <zcode-checkout> | --verify\n',
      );
      process.exit(0);
    }
  }
  return args;
}

function walk(dir, base = dir, out = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const abs = join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(abs, base, out);
    } else if (entry.isFile()) {
      out.push(relative(base, abs).split('\\').join('/'));
    }
  }
  return out;
}

function sha256(abs) {
  return createHash('sha256').update(readFileSync(abs)).digest('hex');
}

function manifestPathFor(dir) {
  return join(packagesRoot, dir, 'vendor-manifest.json');
}

function buildManifest(root, generatedFiles = []) {
  const files = {};
  for (const rel of walk(root).sort()) {
    if (rel === 'vendor-manifest.json') continue;
    if (generatedFiles.includes(rel)) continue;
    files[rel] = sha256(join(root, rel));
  }
  return files;
}

function copyTree(from, to) {
  mkdirSync(to, { recursive: true });
  for (const rel of walk(from).sort()) {
    const dest = join(to, rel);
    mkdirSync(dirname(dest), { recursive: true });
    copyFileSync(join(from, rel), dest);
  }
}

function applyRewrite(root, rewrite) {
  if (rewrite === null) return [];
  const changed = [];
  for (const rel of walk(join(root, 'src'))) {
    if (!rel.endsWith('.ts')) continue;
    const abs = join(root, 'src', rel);
    const before = readFileSync(abs, 'utf8');
    if (!before.includes(rewrite.from)) continue;
    writeFileSync(abs, before.split(rewrite.from).join(rewrite.to));
    changed.push(rel);
  }
  return changed;
}

function syncPackage(pkg, upstreamRoot) {
  const upstream = join(upstreamRoot, pkg.upstream);
  if (!existsSync(join(upstream, 'src', 'index.ts'))) {
    process.stderr.write(
      `error: ${upstream} does not look like ${pkg.dir} (missing src/index.ts)\n`,
    );
    process.exit(1);
  }
  const target = join(packagesRoot, pkg.dir);
  process.stdout.write(`vendoring ${pkg.dir} from ${upstream}\n`);

  rmSync(join(target, 'src'), { recursive: true, force: true });
  rmSync(join(target, 'docs'), { recursive: true, force: true });
  rmSync(join(target, 'scripts'), { recursive: true, force: true });
  rmSync(join(target, 'tsconfig.json'), { force: true });
  rmSync(join(target, 'README.md'), { force: true });
  mkdirSync(target, { recursive: true });

  copyTree(join(upstream, 'src'), join(target, 'src'));
  for (const file of ['tsconfig.json', ...pkg.extraFiles]) {
    const src = join(upstream, file);
    if (!existsSync(src)) continue;
    const dest = join(target, file);
    mkdirSync(dirname(dest), { recursive: true });
    copyFileSync(src, dest);
  }
  for (const doc of pkg.docs) {
    const src = join(upstream, doc);
    if (!existsSync(src)) continue;
    const dest = join(target, doc);
    mkdirSync(dirname(dest), { recursive: true });
    copyFileSync(src, dest);
  }

  const changed = applyRewrite(target, pkg.rewriteImport);
  if (changed.length > 0) {
    process.stdout.write(
      `  rewrote import specifier in: ${changed.join(', ')}\n` +
        `  ${pkg.rewriteImport.from} -> ${pkg.rewriteImport.to}\n`,
    );
  }

  writeManifest(pkg, target);
  return Object.keys(buildManifest(target, pkg.generatedFiles)).length;
}

function writeManifest(pkg, target) {
  const files = buildManifest(target, pkg.generatedFiles);
  const local = {};
  const upstreamFiles = {};
  for (const [rel, hash] of Object.entries(files)) {
    if (pkg.localFiles.includes(rel)) local[rel] = hash;
    else upstreamFiles[rel] = hash;
  }
  const payload = {
    _comment:
      'Hashes of the vendored ZCode tree. Regenerate with ' +
      'scripts/vendor-dynamic-workflow.mjs --from <zcode-checkout>. Verify with ' +
      '--verify. Do not hand-edit. `upstreamFiles` must stay byte-identical to ' +
      'zai-org/ZCode (except the recorded import-specifier rewrite); `localFiles` ' +
      'are ours but tracked so edits are visible.',
    upstream: 'https://github.com/zai-org/ZCode',
    package: pkg.upstream,
    ...(pkg.rewriteImport === null
      ? {}
      : { importRewrite: { ...pkg.rewriteImport, files: 'see sync output' } }),
    fileCount: Object.keys(files).length,
    upstreamFiles,
    localFiles: local,
  };
  writeFileSync(manifestPathFor(pkg.dir), `${JSON.stringify(payload, null, 2)}\n`);
}

function verifyPackage(pkg) {
  const manifestPath = manifestPathFor(pkg.dir);
  if (!existsSync(manifestPath)) {
    process.stderr.write(`error: ${pkg.dir}/vendor-manifest.json missing; run a sync first\n`);
    process.exit(1);
  }
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
  const target = join(packagesRoot, pkg.dir);
  const actual = buildManifest(target, pkg.generatedFiles);
  const problems = [];
  const expected = { ...(manifest.upstreamFiles ?? {}), ...(manifest.localFiles ?? {}) };

  for (const [rel, hash] of Object.entries(expected)) {
    if (actual[rel] === undefined) problems.push(`missing: ${rel}`);
    else if (actual[rel] !== hash) problems.push(`modified: ${rel}`);
  }
  for (const rel of Object.keys(actual)) {
    if (expected[rel] === undefined) problems.push(`unexpected: ${rel}`);
  }

  if (problems.length > 0) {
    process.stderr.write(`${pkg.dir}: vendored tree drifted from the manifest:\n`);
    for (const p of problems) process.stderr.write(`  ${p}\n`);
    process.exit(1);
  }
  const upstreamCount = Object.keys(manifest.upstreamFiles ?? {}).length;
  const localCount = Object.keys(manifest.localFiles ?? {}).length;
  process.stdout.write(
    `${pkg.dir}: matches manifest (${upstreamCount} upstream + ${localCount} local files)\n`,
  );
}

const args = parseArgs(process.argv.slice(2));

if (args.verify) {
  for (const pkg of PACKAGES) verifyPackage(pkg);
} else if (args.from) {
  const upstreamRoot = resolve(args.from);
  if (!existsSync(join(upstreamRoot, 'apps', 'zcode-cli', 'packages'))) {
    process.stderr.write(
      `error: ${upstreamRoot} does not look like a ZCode checkout ` +
        `(missing apps/zcode-cli/packages)\n`,
    );
    process.exit(1);
  }
  let total = 0;
  for (const pkg of PACKAGES) total += syncPackage(pkg, upstreamRoot);
  process.stdout.write(`vendored ${total} files into packages/\n`);
} else {
  process.stderr.write('error: pass --from <zcode-checkout> or --verify\n');
  process.exit(1);
}
